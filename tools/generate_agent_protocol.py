#!/usr/bin/env python3
"""Generate the embedded agent command schema and its reference page from one JSON source."""
import argparse
import copy
import json
from pathlib import Path
import re
import sys

IDENTIFIER = re.compile(r"^[a-z][a-z0-9_]*$")
ACCESS = ("read", "simulate", "modify", "session")


def require(condition, message):
    if not condition:
        raise ValueError(message)


def inline(value, definitions, trail=()):
    """Resolve #/definitions references so each command schema stands alone."""
    if isinstance(value, dict):
        if "$ref" in value:
            reference = value["$ref"]
            require(reference.startswith("#/definitions/"), "unsupported $ref: " + reference)
            name = reference[len("#/definitions/"):]
            require(name in definitions, "unknown definition: " + name)
            require(name not in trail, "recursive definition: " + name)
            merged = copy.deepcopy(definitions[name])
            for key, child in value.items():
                if key != "$ref":
                    merged[key] = child
            return inline(merged, definitions, trail + (name,))
        return {key: inline(child, definitions, trail) for key, child in value.items()}
    if isinstance(value, list):
        return [inline(child, definitions, trail) for child in value]
    return value


def build(source):
    require(isinstance(source.get("protocol"), int) and source["protocol"] >= 2, "protocol must be an integer >= 2")
    definitions = source.get("definitions", {})
    commands = []
    names = set()
    for command in source["commands"]:
        name = command["name"]
        require(isinstance(name, str) and IDENTIFIER.fullmatch(name), "invalid command name: " + repr(name))
        require(name not in names, "duplicate command: " + name)
        names.add(name)
        require(command["access"] in ACCESS, name + ": unknown access " + repr(command["access"]))
        require(isinstance(command["summary"], str) and command["summary"], name + ": summary required")
        params = inline(command["params"], definitions)
        require(params.get("type") == "object", name + ": params must be an object schema")
        for required in params.get("required", []):
            require(required in params.get("properties", {}), name + ": required parameter is not declared: " + required)
        params = {"$schema": "https://json-schema.org/draft/2020-12/schema", **params}
        commands.append({"name": name, "access": command["access"], "summary": command["summary"], "params": params})
    return {"protocol": source["protocol"], "description": source["description"], "commands": commands}



def raw_pieces(text, delimiter):
    """Adjacent raw string literals of at most 8000 characters each: MSVC caps a
    single literal piece at about 16 KB (the concatenation may be longer)."""
    pieces = [text[i:i + 8000] for i in range(0, len(text), 8000)] or [""]
    return "\n    ".join("R\"" + delimiter + "(" + piece + ")" + delimiter + "\"" for piece in pieces)

def header(schema):
    encoded = json.dumps(schema, ensure_ascii=True, separators=(",", ":"))
    delimiter = "POCKET_AGENT"
    require(")" + delimiter + '"' not in encoded, "schema conflicts with the C++ raw string delimiter")
    names = ", ".join('"' + command["name"] + '"' for command in schema["commands"])
    return ("// Generated by tools/generate_agent_protocol.py; edit scripting/api/agent-protocol.json.\n"
            "#ifndef POCKET2D_AGENT_PROTOCOL_SCHEMA_H\n#define POCKET2D_AGENT_PROTOCOL_SCHEMA_H\n"
            "#include <array>\n#include <string_view>\nnamespace PocketAgentProtocol {\n"
            "inline constexpr int kVersion = " + str(schema["protocol"]) + ";\n"
            "inline constexpr std::array<std::string_view, " + str(len(schema["commands"])) + "> kCommands{" + names + "};\n"
            "inline constexpr std::string_view kSchemaJson = " + raw_pieces(encoded, delimiter) + ";\n"
            "} // namespace PocketAgentProtocol\n#endif\n")


def describe_type(schema):
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema.get("type", "value")
    if isinstance(kind, list):
        kind = " | ".join(kind)
    if kind == "array" and isinstance(schema.get("items"), dict):
        kind = describe_type(schema["items"]) + "[]"
    bounds = []
    for key, label in (("minimum", "≥"), ("maximum", "≤"), ("minItems", "min items "), ("maxItems", "max items ")):
        if key in schema:
            bounds.append(label + str(schema[key]))
    return kind + (" (" + ", ".join(bounds) + ")" if bounds else "")


def reference(schema):
    lines = ["# Agent command reference", "",
             "Generated by `tools/generate_agent_protocol.py` from",
             "`scripting/api/agent-protocol.json`; do not edit by hand. Protocol semantics",
             "are described in [agent-protocol.md](agent-protocol.md).", "",
             "Protocol version: " + str(schema["protocol"]) + ".", ""]
    for command in schema["commands"]:
        lines += ["## `" + command["name"] + "`", "", command["summary"], "",
                  "Access: `" + command["access"] + "`.", ""]
        properties = command["params"].get("properties", {})
        if not properties:
            lines += ["No parameters.", ""]
            continue
        required = set(command["params"].get("required", []))
        lines += ["| Parameter | Type | Required | Notes |", "| --- | --- | --- | --- |"]
        for name, child in properties.items():
            notes = child.get("description", "").replace("|", "\\|")
            if "default" in child:
                notes = (notes + " " if notes else "") + "Default " + json.dumps(child["default"]) + "."
            lines.append("| `" + name + "` | " + describe_type(child).replace("|", "\\|") + " | " +
                         ("yes" if name in required else "no") + " | " + notes + " |")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if any generated file is missing or stale")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    options = parser.parse_args()
    try:
        source = json.loads((options.root / "scripting/api/agent-protocol.json").read_text(encoding="utf-8"))
        schema = build(source)
        outputs = {"include/app/runtime/AgentProtocolSchema.h": header(schema),
                   "docs/development/agent-commands.md": reference(schema)}
        stale = []
        for relative, content in outputs.items():
            path = options.root / relative
            if options.check:
                if not path.is_file() or path.read_text(encoding="utf-8") != content:
                    stale.append(relative)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
        if stale:
            print("stale generated agent protocol: " + ", ".join(stale), file=sys.stderr)
            return 1
        print("agent protocol generation " + ("checked" if options.check else "complete"))
        return 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        print("agent protocol generation failed: " + str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
